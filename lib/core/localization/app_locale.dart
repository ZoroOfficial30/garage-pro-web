import 'package:flutter/material.dart';
import '../../data/database/database_service.dart';

enum AppLanguage { en, bn, ar, hi, ur }

class AppLocaleManager extends ChangeNotifier {
  AppLanguage _currentLanguage = AppLanguage.en;

  AppLocaleManager() {
    _loadSavedLanguage();
  }

  void _loadSavedLanguage() {
    try {
      final db = DatabaseService();
      final saved = db.settingsBox.get('app_language');
      if (saved is String) {
        for (final l in AppLanguage.values) {
          if (l.name == saved) {
            _currentLanguage = l;
            break;
          }
        }
      }
    } catch (_) {}
  }

  AppLanguage get currentLanguage => _currentLanguage;

  bool get isBangla => _currentLanguage == AppLanguage.bn;
  bool get isArabic => _currentLanguage == AppLanguage.ar;
  bool get isUrdu => _currentLanguage == AppLanguage.ur;
  bool get isHindi => _currentLanguage == AppLanguage.hi;
  bool get isEnglish => _currentLanguage == AppLanguage.en;

  bool get isRTL =>
      _currentLanguage == AppLanguage.ar || _currentLanguage == AppLanguage.ur;

  TextDirection get textDirection =>
      isRTL ? TextDirection.rtl : TextDirection.ltr;

  Locale get locale => Locale(_currentLanguage.name);

  void toggleLanguage() {
    if (_currentLanguage == AppLanguage.en) {
      setLanguage(AppLanguage.bn);
    } else {
      setLanguage(AppLanguage.en);
    }
  }

  void setLanguage(AppLanguage language) {
    if (_currentLanguage != language) {
      _currentLanguage = language;
      try {
        final db = DatabaseService();
        db.settingsBox.put('app_language', language.name);
      } catch (_) {}
      notifyListeners();
    }
  }

  String translate(String key) {
    return _localizedValues[_currentLanguage]?[key] ??
        _localizedValues[AppLanguage.en]?[key] ??
        key;
  }

